#!/usr/bin/env python3
"""Builds data/replay_2024.json from the saved Open-Meteo responses in evidence/openmeteo. Owner: dev#4.
Only numbers we actually computed are written here; reported figures are tagged with their (press) source and 'verify'."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EV = ROOT / "evidence" / "openmeteo"


def daily(path, key):
    h = json.loads(path.read_text())["hourly"]
    s = defaultdict(float)
    for t, v in zip(h["time"], h[key]):
        if v is not None:
            s[t[:10]] += v
    return s


f27 = daily(EV / "previous_runs_2024-07-24_29.json", "precipitation_previous_day1")
o27 = daily(EV / "archive_2024-07-24_29.json", "precipitation")
f28 = daily(EV / "previous_runs_2024-06-26_30.json", "precipitation_previous_day1")
o28 = daily(EV / "archive_2024-06-26_30.json", "precipitation")
out = {
    "_readme": "Generated by scripts/build_replay.py. Model numbers are computed from evidence/openmeteo. Reported figures come from press / court orders and must be verified before being spoken.",
    "model": "Open-Meteo (gridded; Previous Runs day-1 forecast and archive reanalysis) at 28.642 N, 77.186 E",
    "events": [
        {"id": "2024-07-27", "label": "Old Rajinder Nagar basement deaths", "date": "2024-07-27",
         "forecast_day_before_mm_day": round(f27["2024-07-27"], 1), "model_archive_mm_day": round(o27["2024-07-27"], 1),
         "reported_mm": 58, "reported_basis": "evening rainfall, per High Court order via press", "verify": True,
         "reported_outcome": "3 students died (press and inquiry reports)"},
        {"id": "2024-06-28", "label": "Record 24 h rainfall", "date": "2024-06-28",
         "forecast_day_before_mm_day": round(f28["2024-06-28"], 1), "model_archive_mm_day": round(o28["2024-06-28"], 1),
         "reported_mm": 228.1, "reported_basis": "24 h at Safdarjung, per press", "verify": True, "reported_outcome": None},
    ],
    "caveats": [
        "A coarse grid model (10 to 25 km) is not directly comparable with a point gauge or a court-reported figure.",
        "This does not show that no forecast could have worked. It shows that this free model did not forecast these two storms at the scale reported.",
        "So Rain-Ready keys its alerts on official IMD warnings entered by an operator, not on its own prediction.",
    ],
}
(ROOT / "data" / "replay_2024.json").write_text(json.dumps(out, indent=2))
print(json.dumps(out["events"], indent=2))
