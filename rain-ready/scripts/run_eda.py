"""EDA pipeline for Delhi waterlogging records -> data/consolidated/eda.json and docs/EDA_RESULTS.md (method: docs/EDA.md).

Stages (core/eda.py): validate, profile, places, days, roads, ownership, chronic, pilot, insights.
Run from rain-ready/:  python -m scripts.run_eda [--stage NAME]      Needs data/raw/fco_rows.csv and data/raw/pwd_roads.json.
Pilot context is read from data/consolidated/hotspots.json when it exists (python -m scripts.consolidate).
"""
import argparse
import csv
import json
import sys
import time
from pathlib import Path

from core import eda

ROOT = Path(__file__).resolve().parent.parent
RAW, CONS = ROOT / "data" / "raw", ROOT / "data" / "consolidated"


def load() -> tuple[list[dict], list[dict], list[dict]]:
    fco = list(csv.DictReader((RAW / "fco_rows.csv").open(newline="")))
    pwd = json.loads((RAW / "pwd_roads.json").read_text())["roads"]
    cards = json.loads((CONS / "hotspots.json").read_text())["hotspots"] if (CONS / "hotspots.json").exists() else []
    for c in cards:
        c.setdefault("short", c["name"])
    return fco, pwd, cards


def run(stage: str | None = None) -> dict:
    fco, pwd, cards = load()
    res: dict = {}
    log: list[str] = []

    def stage_fn(name, fn):
        t = time.time()
        res[name] = fn()
        log.append(f"{name:<10} {time.time() - t:5.2f}s")

    stage_fn("validate", lambda: eda.validate(fco))
    stage_fn("profile", lambda: eda.profile(fco))
    stage_fn("places", lambda: eda.places(fco))
    stage_fn("days", lambda: eda.days(fco))
    stage_fn("roads", lambda: eda.roads(res["places"]))
    stage_fn("owned", lambda: eda.match_ownership(res["places"], pwd))
    stage_fn("ownership", lambda: eda.ownership_summary(res["owned"]))
    stage_fn("chronic", lambda: sorted(eda.chronic(res["owned"]), key=lambda p: (-p["n_dates"], p["key"])))
    stage_fn("pilot", lambda: eda.pilot_context(cards, res["places"], res["days"]["counts"], res["days"]["median_places"]))
    stage_fn("insights", lambda: eda.insights(res))
    stage_fn("actions", lambda: eda.place_actions(res["owned"]))
    res["_log"] = log
    if stage:
        print(json.dumps(res.get(stage, f"no stage {stage}"), indent=1, default=list)[:6000])
    return res


def to_markdown(r: dict) -> str:
    p, d, o, rd = r["profile"], r["days"], r["ownership"], r["roads"]
    L = ["# Delhi waterlogging records: EDA results", "",
         "Generated by `python -m scripts.run_eda`; do not edit by hand. Method and definitions: `docs/EDA.md`. Generated from the Traffic Police lists in the Flood Control Order 2025 "
         f"({r['validate']['rows']} rows, {p['location_dates']:,} location-dates, {d['n_days']} days, {r['validate']['date_span'][0]} to "
         f"{r['validate']['date_span'][1]}) and the PWD road inventory. Counts are floors: the lists name places that disrupted traffic.", ""]
    L += ["## Insights and actions", ""]
    for i in r["insights"]:
        L += [f"**{i['text']}** {i['why']}", "", f"- Action ({i['action']['type']}): {i['action']['text']}", ""]
    L += ["## Chronic places (listed in 3 or more years)", "", "| Road | Place | Dates | Years | Owner by rule |", "|---|---|---|---|---|"]
    for c in r["chronic"][:15]:
        L.append(f"| {c['road']} | {c['place'][:48]} | {c['n_dates']} | {', '.join(c['years'])} | {(c['agency_id'] or 'unresolved').upper() if c['agency_id'] else 'unresolved'} |")
    L += ["", "## Pilot places against Delhi", "", "| Place | Dates | Recurrence percentile | Dates on ordinary days |", "|---|---|---|---|"]
    for c in r["pilot"]:
        L.append(f"| {c['short']} | {c['n_dates']} | {c['recurrence_percentile'] if c['recurrence_percentile'] is not None else 'in no list'} | {c['ordinary_day_dates']} |")
    L += ["", "## Data quality", "",
          f"- Row numbering gaps: {r['validate']['numbering_gaps']}",
          f"- Duplicate row numbers: {r['validate']['duplicate_numbers']}",
          f"- Rows without dates: {r['validate']['rows_without_dates']}; rows without place text: {r['validate']['rows_without_place']}",
          f"- Road match to the PWD inventory: {o['resolved_share']:.0%} of location-dates ({o['places_unresolved']} places unresolved). "
          f"Close-spelling matches use a 0.88 similarity cut-off; review before relying on one.",
          f"- Road concentration: {rd['n_roads']} road names, top 10 hold {rd['top10_share']:.0%}, Gini {rd['gini']}.", ""]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage")
    a = ap.parse_args(argv)
    r = run(a.stage)
    out = {k: v for k, v in r.items() if k not in ("places", "owned") and not k.startswith("_")}
    out["places"] = r["owned"]
    out["days"] = {k: v for k, v in r["days"].items() if k != "counts"} | {"counts": r["days"]["counts"]}
    (CONS).mkdir(parents=True, exist_ok=True)
    (CONS / "eda.json").write_text(json.dumps(out, indent=1, default=list) + "\n")
    (ROOT / "docs" / "EDA_RESULTS.md").write_text(to_markdown(r))
    print("\n".join(r["_log"]), file=sys.stderr)
    print(f"wrote data/consolidated/eda.json ({len(r['owned'])} places, {len(r['insights'])} insights, {len(r['actions'])} place actions) and docs/EDA_RESULTS.md", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
